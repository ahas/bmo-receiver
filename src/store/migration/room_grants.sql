-- A room member's rights over the room's people, beside its membership: whether it may let a person in and take a
-- member out, kept per room and account the way a membership is (`docs/receiver.md`, 「Console rooms and accounts」).

CREATE TABLE room_grants (
    chat_id bigint NOT NULL,
    account bigint NOT NULL,
    let_in boolean NOT NULL,
    take_out boolean NOT NULL,
    rowid bigint NOT NULL
);

ALTER TABLE room_grants ALTER COLUMN rowid ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME room_grants_rowid_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY room_grants
    ADD CONSTRAINT room_grants_pkey PRIMARY KEY (chat_id, account);

ALTER TABLE ONLY room_grants
    ADD CONSTRAINT room_grants_rowid_key UNIQUE (rowid);

CREATE INDEX room_grants_account ON room_grants USING btree (account);
